USE WAREHOUSE ECOMMERCE_WH;
USE DATABASE ECOMM_DB;
USE SCHEMA RAW;

CREATE OR REPLACE TABLE customer (
    customer_id INT,
    customer_name STRING,
    city STRING,
    email STRING
);

CREATE OR REPLACE TABLE product (
    product_id INT,
    product_name STRING,
    category STRING,
    price NUMBER(10,2)
);

CREATE OR REPLACE TABLE cart (
    cart_id INT,
    customer_id INT,
    created_at TIMESTAMP,
    status STRING
);

CREATE OR REPLACE TABLE orders (
    order_id INT,
    customer_id INT,
    order_amount NUMBER(10,2),
    order_date DATE,
    order_status STRING
);
CREATE OR REPLACE TABLE payment (
    payment_id INT,
    order_id INT,
    payment_amount NUMBER(10,2),
    payment_method STRING,
    payment_status STRING
);
CREATE OR REPLACE TABLE customer_events (
    data VARIANT
);


